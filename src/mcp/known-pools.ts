// ─── Lookup helpers ──────────────────────────────────────────────────────────

/** Find all pools containing both tokens (order-independent) */
export function findPools(tokenA: string, tokenB: string, protocol?: PoolProtocol): KnownPool[] {
  return KNOWN_POOLS_REGISTRY.filter(p => {
    const hasTokens = (p.token0 === tokenA && p.token1 === tokenB) ||
                      (p.token0 === tokenB && p.token1 === tokenA);
    return hasTokens && (!protocol || p.protocol === protocol);
  });
}

/** Get pool by component address */
export function getPool(address: string): KnownPool | undefined {
  return KNOWN_POOLS_REGISTRY.find(p => p.address === address);
}

/** Find best pool for a token pair — lowest fee among pools with both tokens */
export function findBestPool(tokenA: string, tokenB: string, protocol?: PoolProtocol): KnownPool | undefined {
  const pools = findPools(tokenA, tokenB, protocol);
  if (pools.length === 0) return undefined;
  return pools.sort((a, b) => a.feeRateBps - b.feeRateBps)[0];
}
