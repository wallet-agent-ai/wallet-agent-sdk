// ─── Token lookup helpers ─────────────────────────────────────────────────────

/** Resolve symbol OR address → address */
export function resolveTokenAddress(input: string): string {
  if (input.startsWith('resource_')) return input;
  const token = KNOWN_TOKENS.find(t => t.symbol.toLowerCase() === input.toLowerCase());
  if (!token) throw new Error(`Token '${input}' not found. Use resource address directly.`);
  return token.address;
}

/** Resolve address → symbol (fallback: last 8 chars) */
export function resolveTokenSymbol(address: string): string {
  const token = KNOWN_TOKENS.find(t => t.address === address);
  return token?.symbol ?? address.slice(-8);
}

/** Get divisibility for safeDecimal — default 8 if unknown */
export function getTokenDivisibility(address: string): number {
  const token = KNOWN_TOKENS.find(t => t.address === address);
  return token?.divisibility ?? 8;
}

